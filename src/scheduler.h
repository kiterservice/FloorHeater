// Есть ли активный таймер прямо сейчас (для показа значка)
bool schedulerIsTimerActive();

// Вызывается при выходе из экрана настройки таймеров.
// Если сейчас внутри таймера — включает регулятор.
// Если снаружи — состояние регулятора не трогает.
